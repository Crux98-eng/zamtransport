const cors = require('cors');
const express = require('express');
const helmet = require('helmet');
const { rateLimit } = require('express-rate-limit');
const authRoutes = require('./routes/v1/auth');
const adminUserRoutes = require('./routes/v1/admin-users');
const { adminRouter: adminTransportRoutes, publicRouter: publicTransportRoutes } = require('./routes/v1/transport');
const { adminRouter: adminScheduleTripRoutes, driverRouter, commuterRouter, publicRouter: publicScheduleTripRoutes } = require('./routes/v1/schedule-trip');
const { adminRouter: adminTrackingRoutes, driverRouter: driverTrackingRoutes, publicRouter: publicTrackingRoutes } = require('./routes/v1/tracking');
const dashboardRoutes = require('./routes/v1/dashboard');
const notificationRoutes = require('./routes/v1/notifications');
const adminSystemRoutes = require('./routes/v1/admin-system');
const settings = require('./services/settings');
const { errorHandler, notFound } = require('./middlewares/error-handler');

const app = express();
const allowedOrigins = (process.env.CLIENT_URL || 'http://localhost:5173').split(',').map((value) => value.trim()).filter(Boolean);
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin(origin, callback) { if (!origin || allowedOrigins.includes(origin)) return callback(null, true); return callback(new Error('Origin is not allowed by CORS.')); }, credentials: false }));
app.use(express.json({ limit: '100kb' }));
const authRateLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many authentication attempts. Please try again later.', code: 'AUTH_RATE_LIMITED' } });
const trackingRateLimit = rateLimit({ windowMs: 60 * 1000, limit: 120, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many tracking requests. Please try again shortly.', code: 'TRACKING_RATE_LIMITED' } });
app.get('/', (_request, response) => response.json({ success: true, service: 'zambia-transport-api', apiBase: '/api/v1' }));
app.get('/api/v1', (_request, response) => response.json({ success: true, service: 'zambia-transport-api', health: '/health' }));
const publicHealth = (_request, response) => response.json({ status: 'ok', service: 'zambia-transport-api', timestamp: new Date().toISOString() });
app.get('/health', publicHealth);
app.get('/api/v1/health', publicHealth);
app.use(async (request, response, next) => { if (!request.path.startsWith('/api/') || request.path.startsWith('/api/v1/admin') || request.path.startsWith('/api/v1/auth')) return next(); try { if (await settings.get('MAINTENANCE_MODE', 'false') === 'true') return response.status(503).json({ success: false, message: 'The service is temporarily under maintenance.', code: 'MAINTENANCE_MODE' }); next(); } catch (error) { next(error); } });
app.use('/api/v1/auth', authRateLimit, authRoutes);
app.use('/api/v1/admin/users', adminUserRoutes);
app.use('/api/v1/admin', adminTransportRoutes);
app.use('/api/v1/admin', adminScheduleTripRoutes);
app.use('/api/v1/driver', driverRouter);
app.use('/api/v1/commuter', commuterRouter);
app.use('/api/v1/admin', adminTrackingRoutes);
app.use('/api/v1/admin', dashboardRoutes);
app.use('/api/v1/admin', adminSystemRoutes);
app.use('/api/v1/notifications', notificationRoutes);
app.use('/api/v1/driver', driverTrackingRoutes);
app.use('/api/v1', publicTransportRoutes);
app.use('/api/v1', publicScheduleTripRoutes);
app.use('/api/v1', trackingRateLimit, publicTrackingRoutes);
app.use(notFound);
app.use(errorHandler);
module.exports = app;
